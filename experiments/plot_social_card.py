"""Render the GitHub social-preview card -> output/social_card.png (1280x640).

GitHub uses this image as the link preview on Slack / X / LinkedIn. Upload it
under repo Settings -> Social preview. Regenerated by `make figures`.
"""

import matplotlib.pyplot as plt
from matplotlib import font_manager

from ssm.config import OUTPUT

BG      = "#0d1117"   # GitHub dark canvas
FG      = "#e6edf3"
MUTED   = "#8b949e"
ACCENT  = "#3b82f6"

# Prefer a clean sans; fall back to whatever is available.
for family in ("DejaVu Sans", "Arial", "Helvetica"):
    if any(f.name == family for f in font_manager.fontManager.ttflist):
        plt.rcParams["font.family"] = family
        break

fig = plt.figure(figsize=(12.8, 6.4), dpi=100)
fig.patch.set_facecolor(BG)
ax = fig.add_axes([0, 0, 1, 1])
ax.set_facecolor(BG)
ax.set_xlim(0, 1)
ax.set_ylim(0, 1)
ax.axis("off")

ax.plot([0.07, 0.24], [0.80, 0.80], color=ACCENT, lw=3, solid_capstyle="round")

ax.text(0.07, 0.66,
        "A Selective State-Space\nForecaster for BTC",
        fontsize=44, fontweight="bold", color=FG, va="center", linespacing=1.15)

ax.text(0.07, 0.40, "Built from scratch",
        fontsize=22, color=ACCENT, fontweight="bold", va="center")

ax.text(0.07, 0.30,
        "selective scan  ·  logcumsumexp kernel  ·  sparse disjoint-window encoder",
        fontsize=15, color=MUTED, va="center")
ax.text(0.07, 0.235,
        "walk-forward falsification  ·  no mamba-ssm dependency",
        fontsize=15, color=MUTED, va="center")

ax.text(0.07, 0.10, "github.com/doubletrends/state-space-mamba",
        fontsize=14, color=FG, va="center", fontfamily="monospace")

fig.savefig(OUTPUT / "social_card.png", facecolor=BG)
print(f"wrote {OUTPUT / 'social_card.png'}")
